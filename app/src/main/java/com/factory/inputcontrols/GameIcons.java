    public static boolean isGameIcon(int id) {
        return id >= FIRST_ID && id <= LAST_ID;
    }

    /** Items (and alerts) keep the game's colors; the others take the button's color (the style's icon filter). */
    public static boolean keepsColors(int id) {
        Entry entry = FILES.get(id);
        return entry != null && entry.colored;
    }

    public static final int ROWS = 11;

    /** The ids of a picker row (1..ROWS) that have a file in the copied game, in id order. */
    public static int[] available(Context context, int row) {
        File game = new Paths(context).getGame();
        int count = 0;
        int[] ids = new int[FILES.size()];
        for (int i = 0; i < FILES.size(); i++) {
            Entry entry = FILES.valueAt(i);
            if (entry.row == row && new File(game, entry.path).isFile()) ids[count++] = FILES.keyAt(i);
        }
        return java.util.Arrays.copyOf(ids, count);
    }

    /**
     * The shortcut bar's icons are one dark color (brightness 29 of 255) that the game tints light: drawn as they are
     * they'd be dark or grey on the buttons. Such one-color icons become white (their shape kept in the alpha).
     */
    private static Bitmap whitenIfOneColor(Bitmap bitmap) {
        int w = bitmap.getWidth(), h = bitmap.getHeight();
        int[] pixels = new int[w * h];
        bitmap.getPixels(pixels, 0, w, 0, 0, w, h);
        int min = 255, max = 0;
        for (int pixel : pixels) {
            if ((pixel >>> 24) <= 128) continue;
            int lum = (((pixel >> 16) & 0xff) * 299 + ((pixel >> 8) & 0xff) * 587 + (pixel & 0xff) * 114) / 1000;
            if (lum < min) min = lum;
            if (lum > max) max = lum;
        }
        if (max < min || max - min > 12 || min > 200) return bitmap;   // several shades (or already light): as it is
        for (int i = 0; i < pixels.length; i++) pixels[i] = (pixels[i] & 0xff000000) | 0xffffff;
        Bitmap white = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888);
        white.setPixels(pixels, 0, w, 0, 0, w, h);
        return white;
    }

    /** The icon from the copied game, its big mip level only; null without the game or the file. */
    public static Bitmap load(Context context, int id) {
        Entry entry = FILES.get(id);
        if (entry == null) return null;
        File file = new File(new Paths(context).getGame(), entry.path);
        if (!file.isFile()) return null;
        try {
            Bitmap bitmap = BitmapFactory.decodeFile(file.getPath());
            if (bitmap == null) return null;
            int size = bitmap.getHeight();
            if (bitmap.getWidth() > size) bitmap = Bitmap.createBitmap(bitmap, 0, 0, size, size);
            return whitenIfOneColor(bitmap);
        }
        catch (Throwable e) {
            return null;
        }
    }
